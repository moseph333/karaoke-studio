/**
 * Writes the @font-face rules for every typeface the app and the stage name, pointing at the
 * woff2 files of the @fontsource packages in node_modules:
 *
 * - src/fonts.css: the app's own faces (Marquee, the default look, uses them too), loaded
 *   with the first screen.
 * - src/stageFonts.css: the stage looks' faces, loaded with the studio.
 * - src/stageFonts.ktv.css: the Japanese slices of KTV's face (about 120 rules), loaded only
 *   when the KTV look is on.
 *
 * The packages' own CSS cannot be imported as it is: the variable ones call their family
 * "Sora Variable", while the font stacks say "Sora". Run `npm run fonts` after adding a
 * typeface or updating a @fontsource package. Each stage face must be the cut the backend
 * bundles (backend/assets/fonts), whose widths both sides measure text with.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const APP = 'fonts.css';
const STAGE = 'stageFonts.css';
const STAGE_KTV = 'stageFonts.ktv.css';
// A numbered slice ("[42]") of a CJK face, as against a named subset ("latin-ext")
const isSlice = (subset) => /\[\d+\]/.test(subset);

// family as the font stacks spell it → package, the stylesheets to take from it, the file the
// rules go to, and (for a face split over two files) which of its subsets go there
const FONTS = [
  ['Sofia Sans', '@fontsource-variable/sofia-sans', ['index.css'], APP],
  [
    'Sofia Sans Extra Condensed',
    '@fontsource-variable/sofia-sans-extra-condensed',
    ['index.css'],
    APP,
  ],
  ['JetBrains Mono', '@fontsource-variable/jetbrains-mono', ['index.css'], APP],
  ['Newsreader', '@fontsource-variable/newsreader', ['index.css', 'wght-italic.css'], STAGE],
  ['Jost', '@fontsource-variable/jost', ['index.css'], STAGE],
  ['Atkinson Hyperlegible', '@fontsource/atkinson-hyperlegible', ['700.css'], STAGE],
  ['M PLUS Rounded 1c', '@fontsource/m-plus-rounded-1c', ['800.css'], STAGE, (s) => !isSlice(s)],
  ['M PLUS Rounded 1c', '@fontsource/m-plus-rounded-1c', ['800.css'], STAGE_KTV, isSlice],
];

const HEADERS = {
  [APP]: `/*
 * Self-hosted typefaces for the app, so the first paint never waits on another site and the
 * studio keeps its look offline. The stage looks' own faces are in stageFonts.css.
 *
 * Generated by scripts/generate-fonts-css.mjs (npm run fonts) from the @fontsource packages;
 * do not edit by hand. Each file is fetched only when text in its family and unicode range
 * is on screen.
 */
`,
  [STAGE]: `/*
 * Self-hosted typefaces of the stage looks (Songbook, Cinema, Prompter and KTV's Latin
 * subsets; Marquee uses the app's own faces), loaded with the studio.
 *
 * Generated by scripts/generate-fonts-css.mjs (npm run fonts); do not edit by hand.
 */
`,
  [STAGE_KTV]: `/*
 * The Japanese slices of KTV's typeface, loaded only when the KTV look is on. Each slice is
 * fetched only when one of its characters is on screen.
 *
 * Generated by scripts/generate-fonts-css.mjs (npm run fonts); do not edit by hand.
 */
`,
};

const blocks = { [APP]: [], [STAGE]: [], [STAGE_KTV]: [] };
for (const [family, pkg, sheets, target, wanted] of FONTS) {
  for (const sheet of sheets) {
    const css = readFileSync(path.join(root, 'node_modules', pkg, sheet), 'utf8');
    for (const match of css.matchAll(/\/\* (\S+) \*\/\s*@font-face\s*\{([^}]*)\}/g)) {
      if (wanted && !wanted(match[1])) continue;
      const body = match[2]
        .replace(/font-family:[^;]*;/, `font-family: '${family}';`)
        // woff2 only: every browser that runs the app reads it
        .replace(
          /src:[^;]*;/,
          (src) =>
            `src: ${src.match(/url\(\.\/files\/[^)]+\.woff2\)\s*format\('[^']+'\)/)[0].replace('./files/', `../node_modules/${pkg}/files/`)};`
        );
      blocks[target].push(`/* ${match[1]} */\n@font-face {${body}}`);
    }
  }
}

for (const [target, rules] of Object.entries(blocks)) {
  writeFileSync(path.join(root, 'src', target), `${HEADERS[target]}\n${rules.join('\n\n')}\n`);
  console.log(`src/${target}: ${rules.length} @font-face rules`);
}
