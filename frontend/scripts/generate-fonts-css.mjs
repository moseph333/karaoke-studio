/**
 * Writes src/fonts.css: the @font-face rules for every typeface the app and the stage
 * presets name, pointing at the woff2 files of the @fontsource packages in node_modules.
 *
 * The packages' own CSS cannot be imported as it is: the variable ones call their family
 * "Sora Variable", while the font stacks (index.css, theme/stagePresets.ts) say "Sora". Run
 * `npm run fonts` after adding a typeface or updating a @fontsource package.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

// family as the font stacks spell it → package and the stylesheets to take from it
const FONTS = [
  ['Sora', '@fontsource-variable/sora', ['index.css']],
  ['Inter', '@fontsource-variable/inter', ['index.css']],
  ['JetBrains Mono', '@fontsource-variable/jetbrains-mono', ['index.css']],
  ['Montserrat', '@fontsource-variable/montserrat', ['index.css']],
  ['Space Grotesk', '@fontsource-variable/space-grotesk', ['index.css']],
  ['VT323', '@fontsource/vt323', ['index.css']],
];

const blocks = [];
for (const [family, pkg, sheets] of FONTS) {
  for (const sheet of sheets) {
    const css = readFileSync(path.join(root, 'node_modules', pkg, sheet), 'utf8');
    for (const match of css.matchAll(/\/\* (\S+) \*\/\s*@font-face\s*\{([^}]*)\}/g)) {
      const body = match[2]
        .replace(/font-family:[^;]*;/, `font-family: '${family}';`)
        // woff2 only: every browser that runs the app reads it
        .replace(
          /src:[^;]*;/,
          (src) =>
            `src: ${src.match(/url\(\.\/files\/[^)]+\.woff2\)\s*format\('[^']+'\)/)[0].replace('./files/', `../node_modules/${pkg}/files/`)};`
        );
      blocks.push(`/* ${match[1]} */\n@font-face {${body}}`);
    }
  }
}

const header = `/*
 * Self-hosted typefaces for the app and its stage presets, so the first paint never waits
 * on another site and the studio keeps its look offline.
 *
 * Generated by scripts/generate-fonts-css.mjs (npm run fonts) from the @fontsource packages;
 * do not edit by hand. Each file is fetched only when text in its family and unicode range
 * is on screen.
 */
`;

writeFileSync(path.join(root, 'src', 'fonts.css'), `${header}\n${blocks.join('\n\n')}\n`);
console.log(`src/fonts.css: ${blocks.length} @font-face rules`);
